const webGrid = document.querySelector("[data-projects-web]");
const designGrid = document.querySelector("[data-projects-design]");
function projectMarkup(p, lang, dictionary) {
  return `<article class="project-card" data-kind="${p.kind}" data-id="${p.id}"><button class="project-open" type="button"><span class="project-preview"><img src="${p.image}" alt="${p.alt[lang]}" loading="lazy"><span class="view-label">${dictionary.viewLabel}</span></span></button><div class="project-meta"><span>${p.kind === "art" ? dictionary.artLabel : dictionary.webLabel}</span><span>${p.year}</span></div><h3>${p.title}</h3><p>${p.cat[lang]}</p><small>${p.desc[lang]}</small></article>`;
}
function render(lang) {
  const d = translations[lang] || translations.fr;
  webGrid.innerHTML = projects
    .filter((p) => p.kind === "web")
    .sort((a, b) => b.sortDate.localeCompare(a.sortDate))
    .map((p) => projectMarkup(p, lang, d))
    .join("");
  designGrid.innerHTML = projects
    .filter((p) => p.kind === "art")
    .sort((a, b) => b.sortDate.localeCompare(a.sortDate))
    .map((p) => projectMarkup(p, lang, d))
    .join("");
  document
    .querySelectorAll(".project-open")
    .forEach(
      (card) =>
        (card.onclick = () =>
          openProject(
            projects.find(
              (p) => p.id === card.closest(".project-card").dataset.id,
            ),
          )),
    );
}
function applyLanguage(lang) {
  const d = translations[lang] || translations.fr;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = `Chanez Kanoun — ${d.role}`;
  document.querySelectorAll("[data-t]").forEach((el) => {
    if (d[el.dataset.t]) el.textContent = d[el.dataset.t];
  });
  document
    .querySelectorAll("[data-lang]")
    .forEach((b) => b.classList.toggle("active", b.dataset.lang === lang));
  render(lang);
  localStorage.setItem("language", lang);
}
document
  .querySelectorAll("[data-lang]")
  .forEach((b) => (b.onclick = () => applyLanguage(b.dataset.lang)));
document.querySelectorAll("[data-project-choice]").forEach((choice) => {
  choice.addEventListener("click", () => {
    const selected = choice.dataset.projectChoice;
    document.querySelectorAll("[data-project-choice]").forEach((item) => {
      const active = item === choice;
      item.classList.toggle("active", active);
      item.setAttribute("aria-selected", active);
    });
    document.querySelectorAll("[data-project-panel]").forEach((panel) => {
      panel.classList.toggle(
        "active",
        selected === "all" || panel.dataset.projectPanel === selected,
      );
    });
  });
});
const dialog = document.querySelector("[data-dialog]");
function openProject(p) {
  const lang = document.documentElement.lang;
  dialog.classList.toggle(
    "logo-dialog",
    p.id === "pxo-logo" || p.id === "sos-logo",
  );
  dialog.classList.toggle(
    "poster-dialog",
    p.id === "renovtaloc-demi-marge" || p.id === "renovtaloc-quart-v2",
  );
  dialog.dataset.projectId = p.id;
  document.querySelector("[data-dialog-preview]").innerHTML =
    `<img src="${p.image}" alt="${p.alt[lang]}">`;
  document.querySelector("[data-dialog-category]").textContent = p.cat[lang];
  document.querySelector("[data-dialog-index]").textContent =
    `${String(projects.indexOf(p) + 1).padStart(2, "0")} / ${String(projects.length).padStart(2, "0")} · ${p.year}`;
  document.querySelector("[data-dialog-title]").textContent = p.title;
  document.querySelector("[data-dialog-description]").textContent =
    p.desc[lang];
  const dialogLink = document.querySelector("[data-dialog-link]");
  dialogLink.hidden = !p.url;
  if (p.url) dialogLink.href = p.url;
  dialog.showModal();
}
document.querySelector("[data-close]").onclick = () => dialog.close();
dialog.onclick = (e) => {
  if (e.target === dialog) dialog.close();
};
applyLanguage(localStorage.getItem("language") || "fr");
